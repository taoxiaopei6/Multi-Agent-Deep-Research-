def all_300_cases() -> list[TestCase]:
    """返回全部300条测试用例。"""
    return MARKET_RESEARCH_CASES + TECH_ANALYSIS_CASES + KNOWLEDGE_QA_CASES


def get_300_by_category(category: str) -> list[TestCase]:
    """按类别筛选。"""
    return [c for c in all_300_cases() if c.category == category]


def get_300_by_id(case_id: str) -> Optional[TestCase]:
    """按 ID 查找。"""
    for c in all_300_cases():
        if c.id == case_id:
            return c
    return None


def get_300_by_difficulty(difficulty: str) -> list[TestCase]:
    """按难度筛选。"""
    return [c for c in all_300_cases() if c.difficulty == difficulty]


def get_300_stats() -> dict:
    """返回统计信息。"""
    all_c = all_300_cases()
    categories = {}
    for c in all_c:
        categories.setdefault(c.category, 0)
        categories[c.category] += 1
    difficulties = {}
    for c in all_c:
        difficulties.setdefault(c.difficulty, 0)
        difficulties[c.difficulty] += 1
    return {
        "total": len(all_c),
        "categories": categories,
        "difficulties": difficulties,
    }
